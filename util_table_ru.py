"""
Локальная таблица утилизационного сбора РФ (для физических лиц, личное пользование).

Источник: utils-2026.xlsx, лист «Утильсбор», блок «Для личного пользования»,
столбцы «С 1 января 2026 года». Значения сверены с calcus.ru (на 06.2026).

Используется ТОЛЬКО как резерв, когда основной источник (calcus.ru) недоступен.
Основной расчёт всегда идёт через calcus.ru (get_customs_fees_russia), т.к. он
автоматически учитывает изменения законодательства, индексацию по годам, полный
список возрастов и объёмов.

Ключевое правило 2026 года: льготная ставка (3 400 ₽ / 5 200 ₽) для физлица
действует только при мощности ≤ 160 л.с. и объёме ≤ 3.0 л. Свыше 160 л.с. —
коммерческие коэффициенты. Объём > 3.0 л — всегда коммерческий утиль (здесь не
покрывается → возвращаем None, чтобы вызывающий код не показал заниженное значение).

Таблица покрывает только возрасты «0-3» и «3-5» (как в исходном файле).
Для остальных случаев функция возвращает None.
"""

# Коды типов двигателя (как в calcus.ru / map_fuel_type_to_engine_code):
# 1 - бензин, 2 - дизель, 4 - электро, 5 - послед. гибрид, 6 - парал. гибрид
_ELECTRIC_CODES = {4, 5}  # электрички и последовательные гибриды — по мощности, объём не важен

# Каждая запись: (верхняя граница л.с. включительно, утиль «0-3 лет», утиль «3-5 лет»).
# Поиск: первая запись, где power_ls <= верхняя_граница. Последняя запись = «всё, что выше».
# Нижняя граница диапазона ЭКСКЛЮЗИВНА (проверено на calcus.ru: 160 л.с. → льгота, 161 → коммерч.).

# Электрички и последовательные гибриды (объём не учитывается)
_ELECTRIC = [
    (80, 3400, 5200),
    (100, 991200, 1641600),
    (130, 1317600, 1912800),
    (160, 1560000, 2227200),
    (190, 1848000, 2594400),
    (220, 2193600, 3024000),
    (250, 2599200, 3523200),
    (280, 3079200, 4104000),
    (float("inf"), 3648000, 4780800),
]

# Бензин / дизель / параллельный гибрид, объём 1.0–2.0 л (1000–2000 cc включительно)
_ICE_1_2 = [
    (160, 3400, 5200),
    (190, 900000, 1492800),
    (220, 952800, 1584000),
    (250, 1010400, 1677600),
    (280, 1142400, 1838400),
    (310, 1291200, 2011200),
    (340, 1459200, 2203200),
    (370, 1663200, 2412000),
    (400, 1896000, 2640000),
    (430, 2160000, 2892000),
    (460, 2464800, 3168000),
    (500, 2808000, 3468000),
    (float("inf"), 3201600, 3796800),
]

# Бензин / дизель / параллельный гибрид, объём 2.0–3.0 л (2001–3000 cc включительно)
_ICE_2_3 = [
    (160, 3400, 5200),
    (190, 2306800, 3456000),
    (220, 2364000, 3501600),
    (250, 2402400, 3552000),
    (280, 2520000, 3660000),
    (310, 2620800, 3770400),
    (340, 2726400, 3873600),
    (370, 2834400, 3981600),
    (400, 2949600, 4094400),
    (430, 3067200, 4209600),
    (460, 3189600, 4327200),
    (500, 3316800, 4447200),
    (float("inf"), 3448800, 4572000),
]

_AGE_INDEX = {"0-3": 1, "3-5": 2}  # индекс колонки в записи таблицы


def _lookup(table, power_ls, age_col):
    for upper, val_0_3, val_3_5 in table:
        if power_ls <= upper:
            return (val_0_3, val_3_5)[age_col - 1]
    return None


def get_util_fee_ru(volume_cc, power_ls, age_bracket, engine_code):
    """
    Возвращает утилизационный сбор (₽) для физлица/личного пользования по таблице 2026,
    либо None, если случай не покрывается (объём > 3.0 л, возраст 5-7/7+, некорректные данные).

    :param volume_cc: объём двигателя, куб. см
    :param power_ls: мощность, л.с.
    :param age_bracket: "0-3" | "3-5" | "5-7" | "7-0"
    :param engine_code: 1=бензин, 2=дизель, 4=электро, 5=послед.гибрид, 6=парал.гибрид
    """
    age_col = _AGE_INDEX.get(age_bracket)
    if age_col is None:  # 5-7 и 7+ в таблице нет
        return None

    try:
        volume_cc = int(float(volume_cc))
        power_ls = int(float(power_ls))
        engine_code = int(engine_code)
    except (TypeError, ValueError):
        return None

    if power_ls <= 0:
        return None

    if engine_code in _ELECTRIC_CODES:
        return _lookup(_ELECTRIC, power_ls, age_col)

    # ДВС и параллельный гибрид — зависит от объёма
    if volume_cc <= 2000:
        return _lookup(_ICE_1_2, power_ls, age_col)
    if volume_cc <= 3000:
        return _lookup(_ICE_2_3, power_ls, age_col)

    # Объём > 3.0 л — обязательный коммерческий утиль, в льготной таблице не покрывается
    return None
